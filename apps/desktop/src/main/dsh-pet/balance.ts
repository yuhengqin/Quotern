import type { QuotaState } from '../../shared/quota.js';

export type BalanceState =
  | { ok: true; provider: string; shape: 'windows'; data: { monthly: number; monthlyLabel: string; monthlyResetsAt?: string; rolling?: number } }
  | { ok: true; provider: string; shape: 'money'; data: { currency: string; total: string; granted?: string; toppedUp?: string; fullBalance?: string } }
  | { ok: false; provider: string; reason: 'unsupported' | 'credential-missing' | 'fetch-error'; message?: string };

/** The legacy mandatory monthly slot carries one explicitly labelled actual window. */
export function toDshPetBalance(quota: QuotaState | null, selection: string | null): BalanceState {
  const provider = quota?.providers.find(item => item.id === selection);
  const failure = (message: string, reason: 'unsupported' | 'credential-missing' | 'fetch-error' = 'fetch-error'): BalanceState => ({ ok: false, provider: provider?.label ?? selection ?? '未选择', reason, message });
  if (!provider) return failure('请先选择额度来源', 'unsupported');
  if (provider.stale || provider.status !== 'ready') return failure(provider.message ?? (provider.stale ? '额度数据已过期' : '额度暂不可用'), ['not-signed-in', 'expired'].includes(provider.status) ? 'credential-missing' : 'fetch-error');
  const money = (provider.providerId ?? provider.id) === 'deepseek' ? provider.windows.find(window => window.id === 'balance-cny') : undefined;
  if (money) {
    // This exact text is generated by Core from its recorded numeric CNY remaining value.
    const amount = /^¥(\d+\.\d{2})$/.exec(money.valueText ?? '')?.[1];
    return amount ? { ok: true, provider: provider.label, shape: 'money', data: { currency: 'CNY', total: amount } } : failure('余额未知');
  }
  const windows = provider.windows.filter(window => Number.isFinite(window.usedPercent) && window.analysisEligible !== false).sort((a, b) => b.usedPercent - a.usedPercent);
  const window = windows[0];
  if (!window) return failure('该来源尚无可用额度窗口', 'unsupported');
  return { ok: true, provider: provider.label, shape: 'windows', data: { monthly: Math.max(0, Math.min(100, window.usedPercent)), monthlyLabel: window.label, ...(typeof window.resetsAt === 'number' && Number.isFinite(window.resetsAt) ? { monthlyResetsAt: new Date(window.resetsAt * 1000).toISOString() } : {}) } };
}
